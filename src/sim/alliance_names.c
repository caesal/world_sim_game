static const char *roman_suffix(int value) {
    static char buffers[4][24];
    static int index;
    static const struct { int value; const char *text; } parts[] = {
        {100, "C"}, {90, "XC"}, {50, "L"}, {40, "XL"}, {10, "X"},
        {9, "IX"}, {5, "V"}, {4, "IV"}, {1, "I"}
    };
    char *out = buffers[index++ % 4];
    int i;
    if (value <= 1) return "";
    out[0] = '\0';
    for (i = 0; i < (int)(sizeof(parts) / sizeof(parts[0])); i++) {
        while (value >= parts[i].value && strlen(out) + strlen(parts[i].text) < 23) {
            strcat(out, parts[i].text);
            value -= parts[i].value;
        }
    }
    return out;
}

int alliance_name_base_count(void) { return ALLIANCE_NAME_BASE_COUNT; }

const char *alliance_name_base_en(int index) {
    return index >= 0 && index < ALLIANCE_NAME_BASE_COUNT ? base_names_en[index] : "Alliance";
}

const char *alliance_name_base_zh(int index) {
    return index >= 0 && index < ALLIANCE_NAME_BASE_COUNT ? base_names_zh[index] : "\xe5\x90\x8c\xe7\x9b\x9f";
}

void alliance_format_name(int base_index, int suffix_number,
                          char *out_en, size_t out_en_size,
                          char *out_zh, size_t out_zh_size) {
    const char *en = alliance_name_base_en(base_index);
    const char *zh = alliance_name_base_zh(base_index);
    const char *suffix = roman_suffix(suffix_number);
    if (suffix_number <= 1 || !suffix[0]) {
        snprintf(out_en, out_en_size, "%s", en);
        snprintf(out_zh, out_zh_size, "%s", zh);
    } else {
        snprintf(out_en, out_en_size, "%s %s", en, suffix);
        snprintf(out_zh, out_zh_size, "%s %s", zh, suffix);
    }
}
